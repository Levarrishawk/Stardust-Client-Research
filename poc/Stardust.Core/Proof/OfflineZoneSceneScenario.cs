    public static OfflineZoneSceneTranscript Run(IReadOnlyDictionary<string, string>? peer = null)
    {
        peer ??= PeerFixtures();
        using FixtureClient client = new(peer, 2, 85);
        long generation = client.Begin();
        string request = Convert.ToHexString(client.Request), select = Convert.ToHexString(client.Select);
        Check(client.Transport.RetainedOutboundPackets == 1);
        Check(client.Receive(generation, client.Frame("ackSelect")).ReleasedOutboundPackets == 1);
        List<string> controls = new();
        void Receive(byte[] frame)
        {
            SoeInboundDatagramResult result = client.Receive(generation, frame);
            controls.AddRange(result.ControlDatagrams.Select(Convert.ToHexString));
            foreach (byte[] delivered in result.ApplicationPayloads) Array.Fill(delivered, (byte)0);
        }
        // Borrowed reordered inputs are deliberately destroyed after receive.
        byte[] borrowed = client.Frame("start1"); Receive(borrowed); Array.Fill(borrowed, (byte)0);
        borrowed = client.Frame("create"); Receive(borrowed); Array.Fill(borrowed, (byte)0);
        Check(client.Scene.State == ZoneSceneTransitionState.Selecting && client.Scene.Scene is null);
        byte[] corrupt = client.Frame("start0"); corrupt[^1] ^= 1;
        Check(client.Receive(generation, corrupt).RejectedFraming);
        Check(client.Receive(generation, client.Frame("start0")[..^1]).RejectedFraming);
        Check(client.Scene.State == ZoneSceneTransitionState.Selecting);
        Receive(client.Frame("start0"));
        Check(client.Scene.State == ZoneSceneTransitionState.Initializing && client.Scene.StagedCount == 1);
        Check(client.Scene.Scene!.X == 1.5f && client.Scene.Scene.Z == -2.25f && client.Scene.Scene.Y == 3.75f);
        Receive(client.Frame("start0")); // duplicate cannot reroute scene start
        Receive(client.Frame("baseline2")); Receive(client.Frame("baseline0"));
        Check(client.Scene.StagedCount == 1); // partial fragmented application is never dispatched
        Receive(client.Frame("baseline1"));
        Check(client.Scene.StagedCount == 2 && client.Scene.StagedBytes == 85);
        Check(client.ReadyPublications == 0 && client.Transport.RetainedOutboundPackets == 0 && client.Transport.GetRetransmissionDatagrams(200, 100).Count == 0);
        Check(client.Complete(generation - 1, 200) is null);
        Completion completed = client.Complete(generation, 200)!;
        string ready = Convert.ToHexString(completed.Wire);
        Check(ready == "0009D4C2B3A1F6DE4EE2F62BD8");
        Check(client.Complete(generation, 201) is null && client.Transport.RetainedOutboundPackets == 1);
        Check(client.Transport.GetRetransmissionDatagrams(299, 100).Count == 0);
        byte[] retry = client.Transport.GetRetransmissionDatagrams(300, 100).Single();
        Check(retry.SequenceEqual(completed.Wire));
        completed.Wire[0] = 255; // returned wire cannot change retained reliable bytes
        Check(client.Transport.GetRetransmissionDatagrams(400, 100).Single().SequenceEqual(retry));
        Check(client.Receive(generation, client.Frame("ackReady")).ReleasedOutboundPackets == 1);
        Check(client.Transport.RetainedOutboundPackets == 0 && client.Transport.GetRetransmissionDatagrams(500, 100).Count == 0);
        Receive(client.Frame("ready")); Receive(client.Frame("ready"));
        Check(client.Scene.State == ZoneSceneTransitionState.Ready);
        Check(completed.Publication.CopyStagedPayloads()[0].SequenceEqual(System.Text.Encoding.ASCII.GetBytes("SYNTH-CREATE\0\x01")));
        byte[] baseline = [..System.Text.Encoding.ASCII.GetBytes("SYNTH-BASELINE"), ..Enumerable.Range(0, 57).Select(i => (byte)i)];
        Check(completed.Publication.CopyStagedPayloads()[1].SequenceEqual(baseline));
        RunFailures(peer);
        return new(request, select, ready, Convert.ToHexString(retry),
            Array.AsReadOnly(completed.Publication.CopyStagedPayloads().Select(Convert.ToHexString).ToArray()),
            controls.AsReadOnly(), client.Scene.State.ToString(), client.ReadyPublications, client.RejectedFraming,
            new ReadOnlyDictionary<string, string>(peer.ToDictionary(p => p.Key, p => p.Value)));
    }

    private static void RunFailures(IReadOnlyDictionary<string, string> peer)
    {
        foreach (string malformed in new[] { "earlyReady", "badStart" })
        {
            using FixtureClient c = new(peer, 2, 85); long g = c.Begin();
            Reject(() => c.Receive(g, c.Frame(malformed)));
            Check(c.Scene.State == ZoneSceneTransitionState.Failed && c.Transport.State == SoeClientTransportState.Closed);
            Check(c.Complete(g, 200) is null && c.Scene.StagedCount == 0);
        }
        using (FixtureClient wrong = new(peer, 2, 85))
        {
            long g = wrong.Begin(); wrong.Receive(g, wrong.Frame("wrong0"));
            Reject(() => wrong.Receive(g, wrong.Frame("wrong1")));
            Check(wrong.Scene.State == ZoneSceneTransitionState.Failed && wrong.Scene.Scene is null);
        }
        foreach ((int count, int bytes) in new[] { (1, 85), (2, 84) })
        {
            using FixtureClient c = new(peer, count, bytes); long g = c.Begin();
            c.Receive(g, c.Frame("start0")); c.Receive(g, c.Frame("start1")); c.Receive(g, c.Frame("create"));
            c.Receive(g, c.Frame("baseline0")); c.Receive(g, c.Frame("baseline1"));
            Reject(() => c.Receive(g, c.Frame("baseline2")));
            Check(c.Scene.State == ZoneSceneTransitionState.Failed && c.Scene.StagedCount == 0 && c.Scene.StagedBytes == 0);
            Check(c.Transport.RetainedOutboundPackets == 0 && c.Complete(g, 300) is null);
        }
        using FixtureClient cancelled = new(peer, 2, 85);
        long old = cancelled.Begin();
        cancelled.Receive(old, cancelled.Frame("start0")); // old partial fragment
        cancelled.Receive(old, cancelled.Frame("create")); // old future packet
        SoeClientTransport oldTransport = cancelled.Transport;
        cancelled.Reset();
        Check(oldTransport.State == SoeClientTransportState.Closed && oldTransport.RetainedOutboundPackets == 0);
        Check(cancelled.Complete(old, 300) is null);
        long current = cancelled.Begin();
        Check(cancelled.Receive(old, cancelled.Frame("start1")).ApplicationPayloads.Count == 0);
        Check(cancelled.Scene.State == ZoneSceneTransitionState.Selecting);
        cancelled.Receive(current, cancelled.Frame("start0")); cancelled.Receive(current, cancelled.Frame("start1"));
        Check(cancelled.Scene.StagedCount == 0); // old future create did not survive transport reset
        cancelled.Receive(current, cancelled.Frame("create"));
        cancelled.Receive(current, cancelled.Frame("ackSelect"));
        Completion published = cancelled.Complete(current, 200)!;
        SoeClientTransport replaced = cancelled.Transport;
        long replacement = cancelled.Begin(); // replace after ready is retained, before echo
        Check(replaced.State == SoeClientTransportState.Closed && replaced.RetainedOutboundPackets == 0);
        Check(cancelled.Complete(current, 300) is null && cancelled.Scene.StagedCount == 0);
        Check(!cancelled.Receive(current, cancelled.Frame("ready")).ApplicationPayloads.Any());
        Check(cancelled.Scene.State == ZoneSceneTransitionState.Selecting && replacement > current);
        Check(published.Publication.CopyStagedPayloads().Count == 1); // caller-owned snapshot survives replacement
        cancelled.Dispose();
        Check(cancelled.Scene.State == ZoneSceneTransitionState.Closed && cancelled.Transport.RetainedOutboundPackets == 0);
    }

    private sealed record Completion(ZoneScenePublication Publication, byte[] Wire);
    private sealed class FixtureClient(IReadOnlyDictionary<string, string> peer, int count, int bytes) : IDisposable
    {
        public ZoneSceneTransition Scene { get; } = new(count, bytes);
        public SoeClientTransport Transport { get; private set; } = new();
        public byte[] Request { get; private set; } = [];
        public byte[] Select { get; private set; } = [];
        public int ReadyPublications { get; private set; }
        public int RejectedFraming { get; private set; }
        public byte[] Frame(string name) => Convert.FromHexString(peer[name]);
        public long Begin()
        {
            Transport.Close(); long generation = Scene.BeginSelection(ObjectId);
            Transport = new(); Request = Transport.BeginSession(0x12345678, 32);
            Transport.AcceptSessionResponse(Frame("response"));
            Select = Transport.CreateReliableDatagram(ZoneSceneProtocolCodec.EncodeSelectCharacter(ObjectId), 0);
            return generation;
        }
        public SoeInboundDatagramResult Receive(long generation, ReadOnlySpan<byte> wire)
        {
            if (generation != Scene.Generation) return new(Array.Empty<byte[]>(), null, 0);
            try
            {
                SoeInboundDatagramResult result = Transport.AcceptDatagram(wire);
                if (result.RejectedFraming) RejectedFraming++;
                foreach (byte[] payload in result.ApplicationPayloads)
                {
                    if (payload.Length < 6) throw new InvalidDataException("Application too short for router discriminator.");
                    uint opcode = BinaryPrimitives.ReadUInt32LittleEndian(payload.AsSpan(2));
                    if (opcode == ZoneSceneProtocolCodec.CmdStartSceneOpcode)
                        Scene.AcceptStart(generation, ZoneSceneProtocolCodec.DecodeCmdStartScene(payload));
                    else if (opcode == SceneReadyProtocolCodec.Opcode) Scene.AcceptServerReady(generation, payload);
                    else Scene.Stage(generation, payload); // opaque SYNTH fixtures only; not actual replication
                }
                return result;
            }
            catch { Scene.Fail(generation); Transport.Close(); throw; }
        }
        public Completion? Complete(long generation, long now)
        {
            ZoneScenePublication? publication = Scene.CompleteMinimumResources(generation);
            if (publication is null) return null;
            try
            {
                byte[] wire = Transport.CreateReliableDatagram(publication.CopyReadyMessage(), now);
                ReadyPublications++;
                return new(publication, wire);
            }
            catch { Scene.Fail(generation); Transport.Close(); throw; }
        }
        public void Reset() { Transport.Close(); Scene.Reset(); }
        public void Dispose() { Transport.Close(); Scene.Close(); }
    }
    private static void Check(bool value) { if (!value) throw new InvalidDataException("Offline zone scene fixture assertion failed."); }
    private static void Reject(Action action)
    {
        try { action(); }
        catch (Exception error) when (error is InvalidDataException or InvalidOperationException) { return; }
        throw new InvalidDataException("Offline negative transcript was accepted.");
    }
}



